#!/usr/bin/env bash
# Round 3 finalize: everything that must run AFTER the serving grid, in order,
# on the otherwise-free GPU, then CPU-side analysis + sealing.
set -euo pipefail
CAMP="${SGLANG_VALIDATION_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
WORK="${SGLANG_VALIDATION_WORK:-/workspace/round3-work}"
R3="$CAMP/round3"
EVK="$R3/evidence/kernel"
mkdir -p "$EVK"

echo "=== [1/8] kernel reference per arm ==="
for ARM in main old new; do
  source "$WORK/venv_$ARM/bin/activate"
  python "$R3/scripts/kernel_ab_r3.py" reference "$EVK/ref_$ARM" \
    "$CAMP/configs/kernel_cases.json" > "$EVK/reference_${ARM}.log" 2>&1 \
    || { echo "kernel reference FAILED arm=$ARM"; tail -5 "$EVK/reference_${ARM}.log"; }
  echo "arm=$ARM: $(tail -1 "$EVK/reference_${ARM}.log")"
done

echo "=== [2/8] cross-arm kernel comparison ==="
source "$WORK/venv_main/bin/activate"
python "$R3/scripts/kernel_ab_r3.py" compare "$EVK/ref_main" "$EVK/ref_new" "$EVK/cross_main_vs_new.json" > "$EVK/compare_mn.log"
python "$R3/scripts/kernel_ab_r3.py" compare "$EVK/ref_old" "$EVK/ref_new" "$EVK/cross_old_vs_new.json" > "$EVK/compare_on.log"
tail -2 "$EVK/compare_mn.log"; tail -2 "$EVK/compare_on.log"

echo "=== [3/8] gate matrix + performance analysis ==="
python3 "$R3/scripts/make_gate_matrix.py" > "$R3/results/gate_matrix_stdout.log"
python3 "$R3/scripts/analyze_r3.py" | tee "$R3/results/analyze_stdout.log"

echo "=== [4/8] GSM8K (optional; skip with SKIP_GSM8K=1) ==="
if [ "${SKIP_GSM8K:-0}" != "1" ]; then
  bash "$R3/scripts/run_gsm8k_r3.sh" gsm8k_r3_full 1319 1024 \
    || echo "GSM8K FAILED/BLOCKED (see evidence/accuracy/gsm8k_r3_full/)"
else
  echo "GSM8K skipped by flag"
fi

echo "=== [5/8] deterministic-serving retry (both arms) ==="
for ARM in main new; do
  bash "$R3/scripts/determinism_r3.sh" "$ARM" || true
done

echo "=== [6/8] verdicts + certificate + reports ==="
python3 "$R3/scripts/make_verdicts.py"
python3 "$R3/scripts/make_certificate.py"
python3 "$R3/scripts/make_reports.py"

echo "=== [7/8] seal manifest ==="
# the manifest seals evidence/results/configs/scripts; the audit's own
# outputs (SHA256SUMS, audit_report.*, negative_tests.log) are excluded as
# they are regenerated by every audit run (documented in round3/README.md)
( cd "$CAMP" && find round3 configs patches -type f \
    ! -path 'round3/audit/SHA256SUMS' \
    ! -path 'round3/audit/audit_report.json' \
    ! -path 'round3/audit/audit_report.md' \
    ! -path 'round3/audit/audit_report_raw.log' \
    ! -path 'round3/audit/negative_tests.log' | sort | xargs sha256sum > round3/audit/SHA256SUMS )
wc -l "$R3/audit/SHA256SUMS"

echo "=== [8/8] independent audit ==="
bash "$R3/scripts/audit_round3.sh" 2>&1 | tee "$R3/audit/audit_report_raw.log"
echo "=== finalize done $(date -Is) ==="
