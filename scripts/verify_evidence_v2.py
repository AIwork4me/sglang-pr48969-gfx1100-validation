class Audit:
    def __init__(self, repo: str):
        self.repo = repo
        self.checks = []  # dicts: id, category, status(PASS/FAIL/BLOCKED), detail, evidence
        self.notes = []

    def check(self, cid: str, category: str, ok, detail: str = "", evidence: str = "") -> bool:
        ok = bool(ok)
        self.checks.append({
            "id": cid, "category": category,
            "status": "PASS" if ok else "FAIL",
            "detail": detail, "evidence": evidence,
        })
        print(f"{'PASS' if ok else 'FAIL'}  {cid}" + (f" :: {detail}" if detail else ""))
        return ok

    @property
    def failed(self):
        return [c for c in self.checks if c["status"] == "FAIL"]

    def summary(self):
        n = {s: sum(1 for c in self.checks if c["status"] == s) for s in ("PASS", "FAIL", "BLOCKED")}
        return n


def load_json(path):
    with open(path) as f:
        return json.load(f)


def load_bench_docs(path):
    """sglang bench output files: single JSON doc, except two A_c4 files that
    contain an abandoned attempt appended before the final leg. Return all docs."""
    raw = open(path).read()
    dec = json.JSONDecoder()
    i, docs = 0, []
    while True:
        while i < len(raw) and raw[i] in " \n\r\t":
            i += 1
        if i >= len(raw):
            break
        d, i = dec.raw_decode(raw, i)
        docs.append(d)
    return docs


def decode_ms_series(server_log_path):
    """PR-author methodology: 'Decode batch' lines, #queue-req: 0, running>0,
    ms/step = running / gen-throughput * 1000; drop first line of each
    contiguous running-req segment; median per run."""
    rows = []
    for line in open(server_log_path, errors="replace"):
        m = DEC_LINE.search(line)
        if m:
            running, tps, queued = int(m.group(1)), float(m.group(2)), int(m.group(3))
            if queued == 0 and running > 0 and tps > 0:
                rows.append(running / tps * 1000.0)
    kept, prev, first_of_seg = [], object(), True
    for idx, ms in enumerate(rows):
        # segment = contiguous constant running-req; recompute needs the raw
        # running values, so re-parse them alongside
        kept.append(ms)
    # re-parse with running values for segment detection
    rows2 = []
    for line in open(server_log_path, errors="replace"):
        m = DEC_LINE.search(line)
        if m:
            running, tps, queued = int(m.group(1)), float(m.group(2)), int(m.group(3))
            if queued == 0 and running > 0 and tps > 0:
                rows2.append((running, running / tps * 1000.0))
    seg_start = set()
    prev = None
    for i, (running, _ms) in enumerate(rows2):
        if prev is None or running != prev:
            seg_start.add(i)
        prev = running
    kept = [ms for i, (_r, ms) in enumerate(rows2) if i not in seg_start]
    med = statistics.median(kept) if kept else None
    return len(rows2), kept, med


def feq(a, b, rel=1e-9, absv=1e-9):
    if a is None or b is None:
        return a is None and b is None
    return math.isclose(float(a), float(b), rel_tol=rel, abs_tol=absv)


